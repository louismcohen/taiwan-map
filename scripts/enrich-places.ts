/**
 * Looks up Google Places details for each synced list place and writes them to
 * src/data/placeDetails.ts, downloading a few photos into public/photos/places/.
 * Places already listed there are skipped (including `{ unmatched: true }`); pass
 * --force to refetch everything, or delete one entry to refetch just that place.
 *
 *   pnpm enrich [--force]
 */
import { mkdir, writeFile } from 'node:fs/promises';
import {
  type HourPeriod,
  type HourPoint,
  PLACE_DETAILS,
  type PlaceDetails,
  type PlaceDetailsEntry,
} from '../src/data/placeDetails.ts';
import { SAVED_PLACES } from '../src/data/places.ts';

const KEY = process.env.GOOGLE_PLACES_KEY ?? '';
const PER_PLACE = 3;
const MAX_WIDTH = 800;
const MATCH_KM = 0.5;
const ROOT = new URL('..', import.meta.url);
const OUT = new URL('../src/data/placeDetails.ts', import.meta.url);
const force = process.argv.includes('--force');

if (!KEY) {
  console.error('GOOGLE_PLACES_KEY is not set in .env.local.');
  process.exit(1);
}

interface PlacesHit {
  id?: string;
  displayName?: { text: string };
  location?: { latitude: number; longitude: number };
  websiteUri?: string;
  regularOpeningHours?: {
    weekdayDescriptions?: string[];
    periods?: { open: HourPoint; close?: HourPoint }[];
  };
  editorialSummary?: { text?: string };
  reviewSummary?: { text?: { text?: string } };
  paymentOptions?: { acceptsCashOnly?: boolean };
  photos?: { name: string }[];
}

const FIELD_MASK = [
  'places.id',
  'places.displayName',
  'places.location',
  'places.websiteUri',
  'places.regularOpeningHours',
  'places.editorialSummary',
  'places.reviewSummary',
  'places.paymentOptions',
  'places.photos',
].join(',');

const DETAIL_MASK = FIELD_MASK.replaceAll('places.', '');

function km(a: { lat: number; lng: number }, b: { latitude: number; longitude: number }) {
  const rad = Math.PI / 180;
  const dLat = (b.latitude - a.lat) * rad;
  const dLng = (b.longitude - a.lng) * rad;
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(a.lat * rad) * Math.cos(b.latitude * rad) * Math.sin(dLng / 2) ** 2;
  return 12742 * Math.asin(Math.sqrt(h));
}

function pointOf(p: HourPoint): HourPoint {
  return { day: p.day, hour: p.hour, minute: p.minute };
}

function periodsOf(hit: PlacesHit): HourPeriod[] | undefined {
  const periods = hit.regularOpeningHours?.periods;
  if (!periods?.length) return undefined;
  return periods.map((p) => ({
    open: pointOf(p.open),
    ...(p.close && { close: pointOf(p.close) }),
  }));
}

async function searchText(place: { name: string; lat: number; lng: number }): Promise<PlacesHit | undefined> {
  const res = await fetch('https://places.googleapis.com/v1/places:searchText', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'X-Goog-Api-Key': KEY,
      'X-Goog-FieldMask': FIELD_MASK,
    },
    body: JSON.stringify({
      textQuery: place.name,
      pageSize: 5,
      locationBias: {
        circle: { center: { latitude: place.lat, longitude: place.lng }, radius: MATCH_KM * 1000 },
      },
    }),
  });
  if (!res.ok) throw new Error(`Text search failed for ${place.name}: ${res.status} ${await res.text()}`);
  const { places } = (await res.json()) as { places?: PlacesHit[] };
  return places?.find((p) => p.location && km(place, p.location) < MATCH_KM) ?? places?.[0];
}

async function getById(placeId: string): Promise<PlacesHit | undefined> {
  const res = await fetch(`https://places.googleapis.com/v1/places/${encodeURIComponent(placeId)}`, {
    headers: { 'X-Goog-Api-Key': KEY, 'X-Goog-FieldMask': DETAIL_MASK },
  });
  if (res.status === 404) return undefined;
  if (!res.ok) throw new Error(`Place details failed for ${placeId}: ${res.status} ${await res.text()}`);
  return (await res.json()) as PlacesHit;
}

async function download(photoName: string, file: string) {
  const res = await fetch(`https://places.googleapis.com/v1/${photoName}/media?maxWidthPx=${MAX_WIDTH}&key=${KEY}`);
  if (!res.ok) throw new Error(`Photo download failed: ${res.status}`);
  const ext = res.headers.get('content-type')?.includes('png') ? 'png' : 'jpg';
  const rel = `photos/places/${file}.${ext}`;
  await writeFile(new URL(`public/${rel}`, ROOT), Buffer.from(await res.arrayBuffer()));
  return rel;
}

function serialize(details: Record<string, PlaceDetailsEntry>) {
  return `// Generated by \`pnpm enrich\` (scripts/enrich-places.ts). Delete an entry to refetch that place;
// \`{ unmatched: true }\` keeps a failed lookup from being retried. Photo paths are relative to
// the site root, served from public/.

/** Google Places day/time: \`day\` is 0=Sunday … 6=Saturday (Places API convention). */
export interface HourPoint {
  day: number;
  hour: number;
  minute: number;
}

export interface HourPeriod {
  open: HourPoint;
  /** Absent when the place stays open overnight into a later close, or is 24 hours. */
  close?: HourPoint;
}

/** Places API enrichment for a synced list place, keyed by Google \`cid\` (see places.ts). */
export interface PlaceDetails {
  /** Stable Places ID (\`ChIJ…\`). */
  placeId: string;
  website?: string;
  /** Monday-first display lines from Places, e.g. \`"Tuesday: 12:00 – 2:00 PM"\`. */
  hours?: string[];
  /** Wall-clock periods for computing open-now in \`Asia/Taipei\` later — not a snapshot of openNow. */
  hourPeriods?: HourPeriod[];
  editorial?: string;
  reviewSummary?: string;
  cashOnly?: boolean;
  photos: string[];
}

export type PlaceDetailsEntry = PlaceDetails | { unmatched: true };

export const isPlaceDetails = (entry: PlaceDetailsEntry | undefined): entry is PlaceDetails =>
  !!entry && !('unmatched' in entry);

export const PLACE_DETAILS: Record<string, PlaceDetailsEntry> = ${JSON.stringify(details, null, 2)};
`;
}

async function flush(details: Record<string, PlaceDetailsEntry>) {
  await writeFile(OUT, serialize(details));
}

await mkdir(new URL('public/photos/places/', ROOT), { recursive: true });

const result: Record<string, PlaceDetailsEntry> = force ? {} : { ...PLACE_DETAILS };
let fetched = 0;
let skipped = 0;
let unmatched = 0;

for (const place of SAVED_PLACES) {
  if (!force && result[place.id]) {
    skipped++;
    continue;
  }

  const known = PLACE_DETAILS[place.id];
  const knownId = known && !('unmatched' in known) ? known.placeId : undefined;
  const hit = knownId ? ((await getById(knownId)) ?? (await searchText(place))) : await searchText(place);
  const dist = hit?.location ? km(place, hit.location) : NaN;

  if (!hit?.id || dist > MATCH_KM) {
    result[place.id] = { unmatched: true };
    unmatched++;
    console.log(`? ${place.name} → no match${Number.isFinite(dist) ? ` (${dist.toFixed(2)} km)` : ''}`);
    await flush(result);
    continue;
  }

  const photos: string[] = [];
  for (const [i, photo] of (hit.photos ?? []).slice(0, PER_PLACE).entries()) {
    photos.push(await download(photo.name, `${place.id}-${i + 1}`));
  }

  const hours = hit.regularOpeningHours?.weekdayDescriptions;
  const hourPeriods = periodsOf(hit);
  const editorial = hit.editorialSummary?.text?.trim();
  const reviewSummary = hit.reviewSummary?.text?.text?.trim();
  const cashOnly = hit.paymentOptions?.acceptsCashOnly === true ? true : undefined;
  const website = hit.websiteUri;

  const entry: PlaceDetails = {
    placeId: hit.id,
    ...(website && { website }),
    ...(hours?.length && { hours }),
    ...(hourPeriods?.length && { hourPeriods }),
    ...(editorial && { editorial }),
    ...(reviewSummary && { reviewSummary }),
    ...(cashOnly && { cashOnly }),
    photos,
  };
  result[place.id] = entry;
  fetched++;
  console.log(
    `✓ ${place.name} → ${hit.displayName?.text ?? hit.id} (${photos.length} photos${cashOnly ? ', cash-only' : ''}${hours ? ', hours' : ''})`,
  );
  await flush(result);
}

await flush(result);
console.log(`Done: ${fetched} enriched, ${unmatched} unmatched, ${skipped} skipped.`);
