/**
 * Downloads Google Places photos for each stop and overnight town into public/photos and records
 * them in src/data/photos.ts. Places already listed there are skipped, so pruned entries stay
 * pruned; pass --force to refetch everything, or delete a place's entry to refetch just that one.
 *
 *   pnpm photos [--force]
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { PHOTOS } from '../src/data/photos.ts';
import { NIGHTS, STOPS } from '../src/data/trip.ts';

const KEY = process.env.GOOGLE_PLACES_KEY;
const PER_PLACE = 3;
const MAX_WIDTH = 800;
const ROOT = new URL('..', import.meta.url);

interface Target {
  name: string;
  lat: number;
  lng: number;
  query?: string;
  /** Search radius; matches farther than this are flagged as possibly the wrong place. */
  km: number;
}

interface Place {
  displayName?: { text: string };
  location?: { latitude: number; longitude: number };
  photos?: { name: string }[];
}

if (!KEY) {
  console.error('GOOGLE_PLACES_KEY is not set in .env.local.');
  process.exit(1);
}

const force = process.argv.includes('--force');

const TARGETS: Target[] = [
  ...STOPS.map((s) => ({ name: s.name, lat: s.lat, lng: s.lng, query: s.query, km: 2 })),
  ...Object.values(NIGHTS).flat().map((t) => ({ name: t.name, lat: t.lat, lng: t.lng, query: t.query, km: t.r })),
];

const slug = (name: string) =>
  name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

function km(a: { lat: number; lng: number }, b: { latitude: number; longitude: number }) {
  const rad = Math.PI / 180;
  const dLat = (b.latitude - a.lat) * rad;
  const dLng = (b.longitude - a.lng) * rad;
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(a.lat * rad) * Math.cos(b.latitude * rad) * Math.sin(dLng / 2) ** 2;
  return 12742 * Math.asin(Math.sqrt(h));
}

async function search(target: Target, textQuery: string): Promise<Place | undefined> {
  const res = await fetch('https://places.googleapis.com/v1/places:searchText', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'X-Goog-Api-Key': KEY!,
      'X-Goog-FieldMask': 'places.displayName,places.location,places.photos',
    },
    body: JSON.stringify({
      textQuery,
      pageSize: 5,
      locationBias: {
        circle: { center: { latitude: target.lat, longitude: target.lng }, radius: target.km * 1000 },
      },
    }),
  });
  if (!res.ok) throw new Error(`Text search failed for ${target.name}: ${res.status} ${await res.text()}`);
  const { places } = (await res.json()) as { places?: Place[] };
  // The top match is sometimes a duplicate listing with no photos.
  return places?.find((p) => p.photos?.length) ?? places?.[0];
}

// A short Chinese query can match only the surrounding area, which has no photos; the English name usually finds the sight.
async function findPlace(target: Target) {
  const place = await search(target, target.query ?? target.name);
  return place?.photos?.length || !target.query ? place : ((await search(target, target.name)) ?? place);
}

async function download(photoName: string, file: string) {
  const res = await fetch(`https://places.googleapis.com/v1/${photoName}/media?maxWidthPx=${MAX_WIDTH}&key=${KEY}`);
  if (!res.ok) throw new Error(`Photo download failed: ${res.status}`);
  const ext = res.headers.get('content-type')?.includes('png') ? 'png' : 'jpg';
  await writeFile(new URL(`public/photos/${file}.${ext}`, ROOT), Buffer.from(await res.arrayBuffer()));
  return `photos/${file}.${ext}`;
}

await mkdir(new URL('public/photos/', ROOT), { recursive: true });

const result: Record<string, string[]> = {};
for (const target of TARGETS) {
  if (!force && PHOTOS[target.name]) {
    result[target.name] = PHOTOS[target.name];
    continue;
  }
  const place = await findPlace(target);
  const photos = place?.photos?.slice(0, PER_PLACE) ?? [];
  const dist = place?.location ? km(target, place.location) : NaN;
  const warn = dist > target.km ? `  ⚠ ${dist.toFixed(1)} km away` : '';
  console.log(`${target.name} → ${place?.displayName?.text ?? 'no match'} (${photos.length} photos)${warn}`);

  result[target.name] = [];
  for (const [i, photo] of photos.entries()) {
    result[target.name].push(await download(photo.name, `${slug(target.name)}-${i + 1}`));
  }
}

await writeFile(
  new URL('src/data/photos.ts', ROOT),
  `// Generated by \`pnpm photos\` (scripts/fetch-photos.ts). Remove entries to drop photos; an empty
// list keeps a place from being refetched. Paths are relative to the site root, served from public/.

export const PHOTOS: Record<string, string[]> = ${JSON.stringify(result, null, 2)};
`,
);
